"""Generate docs/data_dictionary.md for the published dbt models.

Column names, order, and types come from the DuckDB warehouse (DUCKDB_PATH);
descriptions and tests come from the dbt .yml files. Exits non-zero, without
writing, if any published column lacks a description or if the .yml files and
the warehouse disagree about which columns exist.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

import duckdb
import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
MODELS_DIR = REPO_ROOT / "otif_dbt" / "models"
DEFAULT_OUTPUT = REPO_ROOT / "docs" / "data_dictionary.md"
PUBLISHED_SCHEMA = "main_marts"
PUBLISHED_MODELS = ["fct_po_lines", "fct_receipts", "mart_supplier_otif_weekly"]


def load_model_specs(models_dir: Path) -> dict[str, dict]:
    """Every model entry from every dbt .yml file, keyed by model name."""
    specs = {}
    for path in sorted(models_dir.rglob("*.yml")):
        doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        for model in doc.get("models", []):
            specs[model["name"]] = model
    return specs


def warehouse_columns(con: duckdb.DuckDBPyConnection, model: str) -> list[tuple[str, str]]:
    return con.execute(
        """SELECT column_name, data_type FROM information_schema.columns
           WHERE table_schema = ? AND table_name = ? ORDER BY ordinal_position""",
        [PUBLISHED_SCHEMA, model],
    ).fetchall()


def describe_test(test) -> str:
    """One readable line for a generic test entry from a .yml file."""
    if isinstance(test, str):
        return test
    (name, spec), = test.items()
    spec = spec or {}
    args = spec.get("arguments", {})
    short = name.removeprefix("dbt_utils.")
    if short == "relationships":
        target = re.sub(r"ref\('(\w+)'\)", r"\1", args["to"])
        text = f"relationships to {target}.{args['field']}"
    elif short == "accepted_values":
        text = f"accepted_values: {', '.join(map(str, args['values']))}"
    elif short == "accepted_range":
        text = f"accepted_range: {args.get('min_value', '')}..{args.get('max_value', '')}"
    elif short == "expression_is_true":
        text = f"expression_is_true: `{args['expression']}`"
    elif short == "unique_combination_of_columns":
        text = f"unique_combination_of_columns: {', '.join(args['combination_of_columns'])}"
    else:
        text = short
    if spec.get("config", {}).get("severity") == "warn":
        text += " (warn)"
    return text


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def check_model(model: str, spec: dict | None, columns: list[tuple[str, str]]) -> list[str]:
    """Problems that make the dictionary incomplete or stale."""
    if spec is None:
        return [f"{model}: no entry in any .yml file under {MODELS_DIR.relative_to(REPO_ROOT)}"]
    if not columns:
        return [f"{model}: not found in schema {PUBLISHED_SCHEMA}; run make run first"]
    problems = []
    documented = {c["name"]: c for c in spec.get("columns", [])}
    built = [name for name, _ in columns]
    if not spec.get("description", "").strip():
        problems.append(f"{model}: model has no description")
    for name in built:
        if not documented.get(name, {}).get("description", "").strip():
            problems.append(f"{model}.{name}: column has no description")
    for name in documented:
        if name not in built:
            problems.append(f"{model}.{name}: documented in .yml but not in the warehouse")
    return problems


def render_model(model: str, spec: dict, columns: list[tuple[str, str]]) -> list[str]:
    documented = {c["name"]: c for c in spec.get("columns", [])}
    lines = [f"## {model}", "", _cell(spec["description"]), ""]
    model_tests = spec.get("data_tests", [])
    if model_tests:
        lines += ["Table-level tests:", ""] + [f"- {_cell(describe_test(t))}" for t in model_tests] + [""]
    lines += ["| Column | Type | Description | Tests |", "|---|---|---|---|"]
    for name, data_type in columns:
        column = documented[name]
        tests = "; ".join(describe_test(t) for t in column.get("data_tests", []))
        lines.append(f"| `{name}` | {data_type} | {_cell(column['description'])} | {_cell(tests)} |")
    return lines + [""]


def build(db_path: Path, output: Path) -> list[str]:
    specs = load_model_specs(MODELS_DIR)
    with duckdb.connect(str(db_path), read_only=True) as con:
        tables = {model: warehouse_columns(con, model) for model in PUBLISHED_MODELS}

    problems = [p for model in PUBLISHED_MODELS for p in check_model(model, specs.get(model), tables[model])]
    if problems:
        return problems

    lines = [
        "# Data dictionary",
        "",
        "Published tables in schema `main_marts`. Generated by `make docs` "
        "(`pipeline/build_data_dictionary.py`) from the dbt .yml files and the DuckDB warehouse; do not edit by hand.",
        "",
    ]
    for model in PUBLISHED_MODELS:
        lines += render_model(model, specs[model], tables[model])
    output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return []


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)
    db_path = os.environ.get("DUCKDB_PATH") or sys.exit("DUCKDB_PATH is not set; see .env.example")

    problems = build(Path(db_path), args.output)
    if problems:
        print("Data dictionary not written:", *problems, sep="\n  ", file=sys.stderr)
        sys.exit(1)
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
